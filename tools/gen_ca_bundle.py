#!/usr/bin/env python3
"""Build the root-CA bundle the ESP32 uses to verify HTTPS servers.

Picks a small set of widely used roots from the system store and writes them to
firmware/lib/hal_esp32/ca_bundle.h in ESP-IDF's x509 bundle format (as used by
WiFiClientSecure::setCACertBundle): a big-endian certificate count, then per root
name_len, key_len, the DER subject and the DER SubjectPublicKeyInfo, sorted by subject.
Only the root that signs a server's chain is looked up and parsed during a handshake, so
the bundle costs almost no RAM, unlike a PEM chain that is parsed whole per connection.

Usage: python3 tools/gen_ca_bundle.py [/etc/ssl/cert.pem]
"""
import base64
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware/lib/hal_esp32/ca_bundle.h"

# Common-name substrings of the roots to include (cover Let's Encrypt, Google,
# Cloudflare/DigiCert, Amazon, Sectigo and GlobalSign-fronted APIs).
WANTED = [
    "ISRG Root X1",
    "ISRG Root X2",
    "GTS Root R1",
    "GTS Root R2",
    "GTS Root R3",
    "GTS Root R4",
    "DigiCert Global Root CA",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "Amazon Root CA 1",
    "Amazon Root CA 2",
    "Amazon Root CA 3",
    "Amazon Root CA 4",
    "USERTrust RSA Certification Authority",
    "USERTrust ECC Certification Authority",
    "SSL.com Root Certification Authority RSA",
    "SSL.com Root Certification Authority ECC",
]
# GlobalSign roots share the CN "GlobalSign"; they are told apart by OU.
GLOBALSIGN_OUS = ("GlobalSign Root CA - R3", "GlobalSign Root CA - R6")


def subject(pem):
    out = subprocess.run(["openssl", "x509", "-noout", "-subject"], input=pem, capture_output=True, text=True)
    return out.stdout.strip()


def der_element(buf, pos):
    """Returns (start, end) of the TLV at pos, and the offset of its contents."""
    length = buf[pos + 1]
    hdr = 2
    if length & 0x80:
        n = length & 0x7F
        length = int.from_bytes(buf[pos + 2 : pos + 2 + n], "big")
        hdr += n
    return pos, pos + hdr + length, pos + hdr


def subject_and_key(der):
    """DER subject Name and SubjectPublicKeyInfo of an X.509 certificate."""
    _, _, cert_body = der_element(der, 0)
    _, _, tbs_body = der_element(der, cert_body)
    fields = []
    pos = tbs_body
    _, tbs_end, _ = der_element(der, cert_body)
    while pos < tbs_end:
        start, end, _ = der_element(der, pos)
        fields.append(der[start:end])
        pos = end
    if fields[0][0] == 0xA0:  # explicit [0] version
        fields = fields[1:]
    # serial, signature algorithm, issuer, validity, subject, subjectPublicKeyInfo
    return fields[4], fields[5]


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/cert.pem").read_text()
    pems = re.findall(r"-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----", src, re.S)
    chosen = {}
    for pem in pems:
        subj = subject(pem)
        cn = re.search(r"CN ?= ?([^,/]+)", subj)
        ou = re.search(r"OU ?= ?([^,/]+)", subj)
        name = cn.group(1).strip() if cn else ""
        unit = ou.group(1).strip() if ou else ""
        label = unit if name == "GlobalSign" else name
        if name in WANTED or (name == "GlobalSign" and unit in GLOBALSIGN_OUS):
            body = "".join(pem.splitlines()[1:-1])
            chosen.setdefault(label, base64.b64decode(body))
    missing = [w for w in WANTED + list(GLOBALSIGN_OUS) if w not in chosen]

    entries = sorted(subject_and_key(der) for der in chosen.values())
    blob = bytearray(len(entries).to_bytes(2, "big"))
    for name, key in entries:
        blob += len(name).to_bytes(2, "big") + len(key).to_bytes(2, "big") + name + key

    lines = [
        "// Generated by tools/gen_ca_bundle.py. Do not edit.",
        "// ESP-IDF x509 bundle. Roots: " + ", ".join(sorted(chosen)),
        "#pragma once",
        "#include <cstdint>",
        "",
        f"static const uint8_t kCaBundle[{len(blob)}] = {{",
    ]
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i : i + 16]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} roots, {len(blob)} bytes -> {OUT}")
    if missing:
        print("  not found in the system store:", ", ".join(missing))


if __name__ == "__main__":
    main()
