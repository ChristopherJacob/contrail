#!/usr/bin/env python3
"""Build firmware/lib/core/data/Stars.cpp from the Yale Bright Star Catalogue.

Downloads the catalogue (BSC5, CDS V/50 fixed-width text; the CDS archive first, then
the identical copy at the Harvard-Smithsonian CfA), keeps stars brighter than
MAG_LIMIT and writes them as a constexpr table. The output is committed, so firmware
builds never need the network.

Usage: python3 tools/gen_stars.py
"""
import gzip
import urllib.request
from pathlib import Path

URLS = [
    "https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz",
    "http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz",
]
MAG_LIMIT = 3.5
OUT = Path(__file__).resolve().parent.parent / "firmware/lib/core/data/Stars.cpp"


def parse(line):
    """(ra, dec, mag) in degrees from one BSC5 record, or None (bytes per the V/50 ReadMe)."""
    if len(line) < 107 or not line[75:77].strip() or not line[102:107].strip():
        return None
    ra = (int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600) * 15
    dec = int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600
    if line[83] == "-":
        dec = -dec
    return ra, dec, float(line[102:107])


def main():
    raw = None
    for url in URLS:
        try:
            raw = gzip.decompress(urllib.request.urlopen(url, timeout=30).read()).decode("latin-1")
            break
        except OSError as e:
            print(f"{url}: {e}")
    if raw is None:
        raise SystemExit("could not download the catalogue")
    stars = sorted(s for s in (parse(l) for l in raw.splitlines()) if s and s[2] <= MAG_LIMIT)
    sirius = [s for s in stars if s[2] < -1.3]
    assert sirius and abs(sirius[0][0] - 101.29) < 0.5, "catalogue layout changed: Sirius not found"
    lines = [
        "// Generated by tools/gen_stars.py from the Yale Bright Star Catalogue (CDS V/50). Do not edit.",
        '#include "Stars.h"',
        "",
        "namespace data {",
        "",
        "const Star kStars[] = {",
    ]
    lines += [f"    {{{ra:.3f}f, {dec:.3f}f, {mag:.2f}f}}," for ra, dec, mag in stars]
    lines += [
        "};",
        "const int kStarCount = sizeof(kStars) / sizeof(kStars[0]);",
        "",
        "}  // namespace data",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(stars)} stars -> {OUT}")


if __name__ == "__main__":
    main()
