#!/usr/bin/env python3
"""Build firmware/lib/core/screens/TreeProfileData.cpp: the Sky View treeline as a const table.

The silhouette comes from buildTreeProfile() (firmware/lib/core/screens/TreeProfile.cpp).
This compiles it with the host C++ compiler, runs it and writes the table, so the firmware
keeps the 2 KB in flash instead of building it in RAM at boot. test_sky fails if the
committed table and buildTreeProfile() disagree: rerun this after changing the builder.

Usage: python3 tools/gen_trees.py   (needs c++ on the PATH)
"""
import subprocess
import tempfile
from pathlib import Path

FW = Path(__file__).resolve().parent.parent / "firmware"
OUT = FW / "lib/core/screens/TreeProfileData.cpp"

DRIVER = r"""
#include <cstdio>
#include "screens/TreeProfile.h"
int main() {
    static scr::TreeProfile p;
    scr::buildTreeProfile(p);
    for (int k = 0; k < scr::trees::kBins; ++k) std::printf("%d%c", p.rho[k], k + 1 < scr::trees::kBins ? ',' : '\n');
    for (int k = 0; k < scr::trees::kBins; ++k) std::printf("%d%c", p.scale[k], k + 1 < scr::trees::kBins ? ',' : '\n');
    std::printf("%a\n", double(p.rhoMin));
}
"""


def rows(values, per=24):
    return "\n".join("        " + ", ".join(values[i : i + per]) + "," for i in range(0, len(values), per))


def main():
    with tempfile.TemporaryDirectory() as tmp:
        drv, exe = Path(tmp) / "drv.cpp", Path(tmp) / "drv"
        drv.write_text(DRIVER)
        # The same language mode as the native test build, whose goldens these pixels feed.
        subprocess.run(
            ["c++", "-std=gnu++17", f"-I{FW}/lib/core", f"-I{FW}/lib/hal", str(drv),
             str(FW / "lib/core/screens/TreeProfile.cpp"), "-o", str(exe)],
            check=True,
        )
        rho, scale, rho_min = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout.split()
    OUT.write_text(
        "// Generated by tools/gen_trees.py from buildTreeProfile() (TreeProfile.cpp). Do not edit.\n"
        '#include "TreeProfile.h"\n\n'
        "namespace scr {\n\n"
        "const TreeProfile kTreeProfile = {\n"
        "    {\n" + rows(rho.split(",")) + "\n    },\n"
        "    {\n" + rows(scale.split(",")) + "\n    },\n"
        f"    {rho_min}f,\n"
        "};\n\n"
        "}  // namespace scr\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
