#!/usr/bin/env python3
"""Pre-render TrueType fonts into 4-bit alpha glyph tables for lib/core/gfx/fonts.

Usage: tools/.venv/bin/python -I tools/gen_font.py [SYMBOL ...]
Regenerates the named fonts (all of them when none are named); Fonts.h always lists every font. Output is committed so firmware builds
never need Python.
"""
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware/lib/core/gfx/fonts"
TTF = ROOT / "tools/fonts"

INTER = "Inter is licensed under the SIL Open Font License 1.1 (tools/fonts/OFL.txt)."
BARLOW = "Barlow Condensed is licensed under the SIL Open Font License 1.1 (tools/fonts/Barlow-OFL.txt)."
EXTRA = "°→↑↓·•›–—…"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)
# The display face sets callsigns, codes, counts and headings: ASCII and a little punctuation.
COND_CHARS = [chr(c) for c in range(32, 127)] + list("·–…")
# The hero sets only callsigns and counts: space through "_" (digits, capitals, punctuation),
# which keeps the three sizes within their 40 KB of flash.
CAPS = [chr(c) for c in range(32, 96)] + list("·–…")

# (symbol, ttf file, pixel size, characters, licence line)
FONTS = [
    ("kFontSmall", "Inter-Medium.ttf", 10, CHARS, INTER),
    ("kFontBody", "Inter-Medium.ttf", 13, CHARS, INTER),
    ("kFontBold", "Inter-Bold.ttf", 16, CHARS, INTER),
    ("kFontTitle", "InterDisplay-Bold.ttf", 22, CHARS, INTER),
    ("kFontHero", "InterDisplay-Black.ttf", 34, CHARS, INTER),
    ("kFontCondHero", "BarlowCondensed-ExtraBold.ttf", 40, CAPS, BARLOW),
    ("kFontCondTitle", "BarlowCondensed-ExtraBold.ttf", 28, COND_CHARS, BARLOW),
    ("kFontCondLabel", "BarlowCondensed-ExtraBold.ttf", 18, COND_CHARS, BARLOW),
]


def render_glyph(font, ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    if w == 0 or h == 0:
        return dict(w=0, h=0, xoff=0, yoff=0, adv=adv, alpha=[])
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    alpha = [(v * 15 + 127) // 255 for v in img.get_flattened_data()]
    return dict(w=w, h=h, xoff=x0, yoff=y0, adv=adv, alpha=alpha)


def gen(symbol, ttf, size, chars, licence):
    font = ImageFont.truetype(str(TTF / ttf), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        g = render_glyph(font, ch)
        g["cp"] = ord(ch)
        g["offset"] = len(data)
        a = g["alpha"]
        if len(a) % 2:
            a = a + [0]
        for i in range(0, len(a), 2):
            data.append((a[i] << 4) | a[i + 1])
        glyphs.append(g)
    glyphs.sort(key=lambda g: g["cp"])
    name = symbol[1:].lower()
    lines = [
        "// Generated by tools/gen_font.py from " + ttf + f" @ {size}px. Do not edit.",
        "// " + licence,
        '#include "Fonts.h"',
        "namespace gfx {",
        f"static const uint8_t {name}_bits[] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t {name}_cps[] = {{")
    lines.append("  " + ",".join(str(g["cp"]) for g in glyphs))
    lines.append("};")
    lines.append(f"static const GlyphInfo {name}_glyphs[] = {{")
    for g in glyphs:
        lines.append(f"  {{{g['offset']},{g['w']},{g['h']},{g['xoff']},{g['yoff']},{g['adv']}}},")
    lines.append("};")
    space = next(g["adv"] for g in glyphs if g["cp"] == 32)
    lines.append(
        f"const FontData {symbol} = {{{name}_bits, {name}_glyphs, {name}_cps, {len(glyphs)}, "
        f"{ascent}, {descent}, {space}}};"
    )
    lines.append("}  // namespace gfx")
    (OUT / f"{name}.cpp").write_text("\n".join(lines) + "\n")
    flash = len(data) + 14 * len(glyphs)  # bitmaps, glyph records (12 bytes) and code points (2)
    print(f"{symbol}: {len(glyphs)} glyphs, {len(data)} bitmap bytes, ~{flash} bytes of flash")
    return flash


def main():
    only = set(sys.argv[1:])
    unknown = only - {f[0] for f in FONTS}
    if unknown:
        sys.exit("unknown font: " + ", ".join(sorted(unknown)))
    OUT.mkdir(parents=True, exist_ok=True)
    decls = "\n".join(f"extern const FontData {f[0]};" for f in FONTS)
    (OUT / "Fonts.h").write_text(
        "// Generated by tools/gen_font.py. Do not edit.\n#pragma once\n"
        '#include "../Font.h"\n\nnamespace gfx {\n' + decls + "\n}  // namespace gfx\n"
    )
    total = sum(gen(*f) for f in FONTS if not only or f[0] in only)
    print(f"~{total} bytes of flash for the fonts generated")


if __name__ == "__main__":
    main()
